from Algoritms import line, binary, hash_set


def run_test(test_name, text, stops, expected):
    res1 = line(text, stops)
    res2 = binary(text, stops)
    res3 = hash_set(text, stops)

    assert res1 == res2 == res3, f"Результаты разных методов не совпадают!\nЛинейный: {res1}\nБинарный: {res2}\nМножество: {res3}"

    assert res1 == expected, f"Тест провален!\nОжидалось: {expected}\nПолучено: {res1}"

    print(f"✅ {test_name} пройден")


# 1. Happy Path: обычный случай
def test_1_normal():
    run_test(
        "Тест 1: Обычное удаление слов",
        text="мама мыла раму быстро и качественно",
        stops=["и", "быстро"],
        expected="мама мыла раму качественно"
    )


# 2. Краевой случай: пустой текст
def test_2_empty_text():
    run_test(
        "Тест 2: Пустой текст",
        text="",
        stops=["а", "и", "но"],
        expected=""
    )


# 3. Краевой случай: пустой список стоп-слов
def test_3_empty_stop_words():
    run_test(
        "Тест 3: Пустой список стоп-слов",
        text="раз два три четыре пять",
        stops=[],
        expected="раз два три четыре пять"
    )


# 4. Краевой случай: все слова удаляются
def test_4_all_removed():
    run_test(
        "Тест 4: Все слова являются стоп-словами",
        text="кот собака попугай хомяк",
        stops=["кот", "собака", "попугай", "хомяк"],
        expected=""
    )


# 5. Большой текст: всё в одну строку, все слова с маленькой буквы
def test_5_large_text():
    large_text = "в начале было слово и слово было у бога и слово было бог оно было в начале у бога все чрез него начало быть и без него ничто не начало быть в нем была жизнь и жизнь была свет человеков и свет во тьме светит и тьма не объяла его был человек посланный от бога имя ему иоанн он пришел для свидетельства чтобы свидетельствовать о свете был свет истинный который просвещает всякого человека приходящего в мир"

    stops = ["и", "в", "не", "что", "он", "его", "от", "был", "было", "о", "с", "у", "к", "но", "как"]

    expected = "начале слово слово бога слово бог оно начале бога все чрез него начало быть без него ничто начало быть нем была жизнь жизнь была свет человеков свет во тьме светит тьма объяла человек посланный бога имя ему иоанн пришел для свидетельства чтобы свидетельствовать свете свет истинный который просвещает всякого человека приходящего мир"

    run_test(
        "Тест 5: Большой текст (50+ слов)",
        text=large_text,
        stops=stops,
        expected=expected
    )


